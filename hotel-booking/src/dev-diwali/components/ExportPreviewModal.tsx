import { FileSpreadsheet, FileText } from 'lucide-react';
import { DemoBanner, Modal } from './ui/primitives';

/** Mock export: shows what the file would contain. No file is generated in the prototype. */
export function ExportPreviewModal({
  title,
  format,
  columns,
  rows,
  onClose,
}: {
  title: string;
  format: 'CSV' | 'PDF';
  columns: string[];
  rows: (string | number)[][];
  onClose: () => void;
}) {
  const preview = rows.slice(0, 8);
  return (
    <Modal
      title={`Export ${format}: ${title}`}
      subtitle={`${rows.length} rows · preview of the first ${preview.length}`}
      onClose={onClose}
      size="wide"
      footer={
        <button type="button" className="dd-btn dd-btn--primary" onClick={onClose}>
          Close preview
        </button>
      }
    >
      <div className="dd-stack">
        <DemoBanner>
          <strong>Mock export.</strong> In production this downloads a {format} generated by the server from live data. Nothing is
          downloaded in the prototype.
        </DemoBanner>
        <div className="dd-row dd-muted dd-small" style={{ gap: 6 }}>
          {format === 'CSV' ? <FileSpreadsheet size={16} aria-hidden="true" /> : <FileText size={16} aria-hidden="true" />}
          tripomonk-dev-deepawali-{title.toLowerCase().replace(/[^a-z0-9]+/g, '-')}.{format.toLowerCase()}
        </div>
        <div className="dd-table-wrap">
          <table className="dd-table">
            <thead>
              <tr>
                {columns.map((c) => (
                  <th key={c}>{c}</th>
                ))}
              </tr>
            </thead>
            <tbody>
              {preview.map((r, i) => (
                <tr key={i}>
                  {r.map((c, j) => (
                    <td key={j} className="dd-num" style={{ textAlign: 'left' }}>{c}</td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>
    </Modal>
  );
}
