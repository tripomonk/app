import { useRef, useState } from 'react';
import { Copy, Download, Eye, Globe, Hotel as HotelIcon, Info } from 'lucide-react';
import { DIRECT_QR_URL, HOTEL_QR_URL } from '../../data/mockDevDiwaliData';
import { useMockStore } from '../../state/MockStore';
import { useToast } from '../../state/Toasts';
import { QRPosterPreview } from '../../components/QRPosterPreview';
import { HotelThumb } from '../../components/Thumbs';
import { Badge, StatusBadge } from '../../components/ui/primitives';
import { PageHead } from './saShared';

export function QRCodesPage() {
  const { hotels, bookings, admins, hotelById } = useMockStore();
  const toast = useToast();
  const firstActive = hotels.find((h) => h.status === 'Active')?.id ?? '';
  const [selected, setSelected] = useState(firstActive);
  const hotel = hotelById(selected) ?? null;
  const topRef = useRef<HTMLDivElement>(null);

  const copy = async (text: string) => {
    try {
      await navigator.clipboard.writeText(text);
      toast('Link copied.', 'good');
    } catch {
      toast(`Copy not available here — the link is ${text}`, 'info');
    }
  };

  const download = (what: string) =>
    toast(`Demo: a print-ready ${what} poster will be generated by the backend. Nothing was downloaded.`, 'demo');

  return (
    <div className="dd-stack-lg" ref={topRef}>
      <PageHead
        title="QR Codes & Sales Channels"
        description="Two QR posters, two attribution flows. Both open the same /dev-diwali booking page."
      />

      <div className="dd-callout">
        <Info aria-hidden="true" />
        <span>
          The <span className="dd-kbd">?src=</span> parameter and the printed hotel code drive only the preview flows in this prototype. In
          production the backend must verify attribution before a booking counts as a hotel-partner booking.
        </span>
      </div>

      <div className="dd-grid-2 dd-sa-qr-grid">
        <section className="dd-card" aria-labelledby="sa-qr-hotel">
          <div className="dd-card-head">
            <div className="dd-row" style={{ gap: 8 }}>
              <HotelIcon size={18} aria-hidden="true" color="var(--dd-blue)" />
              <h2 id="sa-qr-hotel">Hotel Partner QR</h2>
            </div>
            <Badge tone="blue">Universal QR + printed code</Badge>
          </div>
          <div className="dd-card-body dd-stack">
            <div className="dd-field">
              <label className="dd-label" htmlFor="sa-qr-hotel-select">Hotel</label>
              <select id="sa-qr-hotel-select" className="dd-select" value={selected} onChange={(e) => setSelected(e.target.value)}>
                {hotels.map((h) => (
                  <option key={h.id} value={h.id}>
                    {h.name} · {h.code}{h.status === 'Inactive' ? ' (inactive)' : ''}
                  </option>
                ))}
              </select>
            </div>
            <div className="dd-sa-poster-stage">
              <QRPosterPreview variant="hotel" hotel={hotel} width={280} />
            </div>
            {hotel?.status === 'Inactive' && (
              <div className="dd-callout dd-callout--warn">
                <Info aria-hidden="true" />
                <span>{hotel.name} is inactive, so code {hotel.code} would not match on the booking page.</span>
              </div>
            )}
            <dl className="dd-dl">
              <dt>QR opens</dt>
              <dd><span className="dd-sa-url">{HOTEL_QR_URL}</span></dd>
              <dt>Printed code</dt>
              <dd>{hotel ? <span className="dd-code">{hotel.code}</span> : '—'}</dd>
              <dt>Flow</dt>
              <dd className="dd-muted">Same QR for every hotel. The guest picks their hotel or types the printed code; the code identifies the partner.</dd>
              <dt>Commission</dt>
              <dd className="dd-muted">Eligible under the configured rule (demo)</dd>
            </dl>
            <div className="dd-row">
              <button type="button" className="dd-btn dd-btn--primary" onClick={() => download(hotel ? `${hotel.name} (${hotel.code})` : 'hotel')}>
                <Download /> Download poster
              </button>
              <button type="button" className="dd-btn dd-btn--secondary" onClick={() => copy(HOTEL_QR_URL)}>
                <Copy /> Copy link
              </button>
            </div>
          </div>
        </section>

        <section className="dd-card" aria-labelledby="sa-qr-direct">
          <div className="dd-card-head">
            <div className="dd-row" style={{ gap: 8 }}>
              <Globe size={18} aria-hidden="true" color="#eb6834" />
              <h2 id="sa-qr-direct">Tripomonk Direct QR</h2>
            </div>
            <Badge tone="direct">Direct marketing</Badge>
          </div>
          <div className="dd-card-body dd-stack">
            <div className="dd-field">
              <span className="dd-label">Channel</span>
              <div className="dd-sa-channel-pill">Booking Channel: Tripomonk Direct</div>
            </div>
            <div className="dd-sa-poster-stage">
              <QRPosterPreview variant="direct" width={280} />
            </div>
            <dl className="dd-dl">
              <dt>QR opens</dt>
              <dd><span className="dd-sa-url">{DIRECT_QR_URL}</span></dd>
              <dt>Printed code</dt>
              <dd className="dd-muted">None</dd>
              <dt>Flow</dt>
              <dd className="dd-muted">No hotel selection required. Choosing a stay later does not turn it into a hotel-partner booking.</dd>
              <dt>Commission</dt>
              <dd className="dd-muted">No hotel commission by default</dd>
            </dl>
            <div className="dd-row">
              <button type="button" className="dd-btn dd-btn--primary" onClick={() => download('Tripomonk Direct')}>
                <Download /> Download poster
              </button>
              <button type="button" className="dd-btn dd-btn--secondary" onClick={() => copy(DIRECT_QR_URL)}>
                <Copy /> Copy link
              </button>
            </div>
          </div>
        </section>
      </div>

      <section className="dd-card">
        <div className="dd-card-head">
          <h2>Hotel attribution codes</h2>
          <span className="dd-small dd-muted">Codes are issued by Tripomonk; Hotel Admins cannot change them.</span>
        </div>
        <div className="dd-card-body" style={{ padding: 0 }}>
          <div className="dd-sa-flush">
            <div className="dd-table-wrap">
              <table className="dd-table">
                <caption className="dd-sr-only">Hotel attribution codes</caption>
                <thead>
                  <tr>
                    <th scope="col">Hotel</th>
                    <th scope="col">Printed code</th>
                    <th scope="col">Status</th>
                    <th scope="col" className="dd-num">Hotel Admins</th>
                    <th scope="col" className="dd-num">Attributed bookings</th>
                    <th scope="col"><span className="dd-sr-only">Actions</span></th>
                  </tr>
                </thead>
                <tbody>
                  {hotels.map((h) => (
                    <tr key={h.id}>
                      <td>
                        <div className="dd-row" style={{ gap: 10, flexWrap: 'nowrap' }}>
                          <HotelThumb tint={h.tint} label={h.name} size={34} />
                          <span className="dd-cell-title">{h.name}</span>
                        </div>
                      </td>
                      <td><span className="dd-code">{h.code}</span></td>
                      <td><StatusBadge kind="record" value={h.status} /></td>
                      <td className="dd-num">{admins.filter((a) => a.hotelId === h.id).length}</td>
                      <td className="dd-num">{bookings.filter((b) => b.hotelId === h.id).length}</td>
                      <td>
                        <button
                          type="button"
                          className="dd-btn dd-btn--secondary dd-btn--sm"
                          aria-pressed={selected === h.id}
                          onClick={() => {
                            setSelected(h.id);
                            topRef.current?.scrollIntoView({ behavior: 'smooth', block: 'start' });
                          }}
                        >
                          <Eye /> Preview poster
                        </button>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>
        </div>
      </section>
    </div>
  );
}
